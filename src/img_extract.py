"""
Image extraction and description utilities for NotesAssistant.
Handles conversion of images to text descriptions using LLM.
"""

import base64
import hashlib
import os
import shutil
from datetime import datetime, timezone
from email.utils import parsedate_to_datetime

import openai
from langchain_core.messages import HumanMessage
from tenacity import retry, retry_if_exception, stop_after_attempt, wait_exponential

from settings import LLM_MODEL, PDF_DPI

PAGE_PROMPT = "Describe the image sent. Send it as plain text in paragraphs with no formatting"


def _is_transient(error):
    """
    True for errors that can go away on their own, so retrying is worthwhile.

    503 is excluded on purpose: FreeLLMAPI returns it when no provider key is
    configured or every route is exhausted, which a few seconds of backoff
    won't fix. Bad requests, auth errors and unknown models fail at once too.
    """
    if isinstance(error, (openai.RateLimitError, openai.APIConnectionError)):
        return True  # APIConnectionError also covers timeouts
    if isinstance(error, openai.InternalServerError):
        return error.status_code != 503
    return False


MAX_RETRY_AFTER = 120  # seconds; don't wait longer than this even if the server asks
_backoff = wait_exponential(multiplier=4, max=60)  # 4, 8, 16, 32s


def _retry_after_seconds(error):
    """
    Reads the server's Retry-After hint from an API error, if it sent one.

    Supports retry-after-ms (OpenAI) and Retry-After in seconds or as an
    HTTP date (the standard forms). Returns None if there is no usable hint.
    """
    response = getattr(error, "response", None)
    if response is None:
        return None
    headers = response.headers
    try:
        if "retry-after-ms" in headers:
            return float(headers["retry-after-ms"]) / 1000
        value = headers.get("retry-after")
        if value is None:
            return None
        try:
            return float(value)
        except ValueError:
            retry_at = parsedate_to_datetime(value)
            return (retry_at - datetime.now(timezone.utc)).total_seconds()
    except (TypeError, ValueError):
        return None


def _wait(retry_state):
    """Waits as long as the server's Retry-After says, else exponential backoff."""
    hint = _retry_after_seconds(retry_state.outcome.exception())
    if hint is not None and hint >= 0:
        return min(hint, MAX_RETRY_AFTER)
    return _backoff(retry_state)


def _log_retry(retry_state):
    error = retry_state.outcome.exception()
    print(f"  {type(error).__name__}: {error}. Retrying in {retry_state.next_action.sleep:.0f}s...")


@retry(
    retry=retry_if_exception(_is_transient),
    stop=stop_after_attempt(5),
    # Follows Retry-After when sent; otherwise about a minute in total, enough for a per-minute limit to reset
    wait=_wait,
    before_sleep=_log_retry,
    reraise=True,
)
def img_to_llm(image_file_path, llm):
    """
    Passes an image to the LLM and returns a description of the image.

    This is the only retry layer for ingestion, so the LLM passed in should
    be created with max_retries=0 to avoid retrying inside each attempt.

    Args:
        image_file_path (str): Path to the image file.
        llm: The language model instance to use.

    Returns:
        str: Description of the image generated by the LLM.
    """
    with open(image_file_path, "rb") as image_file:
        encoded_image = base64.b64encode(image_file.read()).decode("utf-8")

    message = HumanMessage(
        content=[
            {"type": "text", "text": PAGE_PROMPT},
            {
                "type": "image_url",
                "image_url": {"url": f"data:image/jpeg;base64,{encoded_image}"},
            },
        ]
    )
    return llm.invoke([message]).content


def page_cache_dir(pdf_path, cache_root):
    """
    Returns the cache folder for one PDF under the current extraction settings.

    The path is <cache_root>/<pdf hash>/<settings hash>. Changing the prompt,
    the model or the dpi gives a new folder, so stale text is never reused.

    Args:
        pdf_path (str): Path to the PDF being indexed.
        cache_root (str): Root folder for all cached page text.

    Returns:
        str: Folder holding page_NNN.txt files for this PDF and settings.
    """
    file_hash = hashlib.sha256()
    with open(pdf_path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            file_hash.update(block)
    settings_key = f"{PAGE_PROMPT}\n{LLM_MODEL}\n{PDF_DPI}".encode("utf-8")
    settings_hash = hashlib.sha256(settings_key).hexdigest()
    return os.path.join(cache_root, file_hash.hexdigest()[:16], settings_hash[:12])


def img_to_txt(output_path, num_pages, llm, cache_dir):
    """
    Converts page images to text and saves them to output_text.

    Each page's text is cached as soon as it comes back, so a re-run only
    calls the LLM for pages that aren't cached yet. If a page fails, the
    pages before it are kept and the next run picks up from there.

    Args:
        output_path (str): Directory containing image files and where text files will be saved.
        num_pages (int): Number of images/pages to process.
        llm: The language model instance to use.
        cache_dir (str): Folder from page_cache_dir() for this PDF.

    Returns:
        None
    """
    text_folder = os.path.join(output_path, "output_text")
    os.makedirs(text_folder, exist_ok=True)
    os.makedirs(cache_dir, exist_ok=True)

    calls = 0
    for i in range(num_pages):
        page_name = f"page_{i+1:03}"
        cached_file = os.path.join(cache_dir, f"{page_name}.txt")

        if os.path.exists(cached_file):
            print(f"Page {i+1}/{num_pages}: cached")
        else:
            print(f"Page {i+1}/{num_pages}: calling LLM")
            image_filename = os.path.join(output_path, f"{page_name}.jpg")
            try:
                llm_output = img_to_llm(image_filename, llm)
            except Exception:
                print(f"Page {i+1} failed. {i} of {num_pages} pages are cached; re-run to resume.")
                raise
            calls += 1
            # Write to a temp file first so a crash can't leave a half-written cache entry
            tmp_file = cached_file + ".tmp"
            with open(tmp_file, "w", encoding="utf-8") as f:
                f.write(llm_output)
            os.replace(tmp_file, cached_file)

        shutil.copyfile(cached_file, os.path.join(text_folder, f"{page_name}.txt"))

    print(f"Text extraction done: {calls} LLM calls, {num_pages - calls} pages from cache.")
